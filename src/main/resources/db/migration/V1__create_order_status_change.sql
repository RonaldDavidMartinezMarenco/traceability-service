CREATE TABLE order_status_change (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    customer_id BIGINT NOT NULL,
    restaurant_id BIGINT NOT NULL,
    employee_id BIGINT,
    previous_status VARCHAR(20),
    new_status VARCHAR(20) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT trace_status_known CHECK (
        new_status IN ('PENDING', 'IN_PREPARATION', 'READY', 'DELIVERED', 'CANCELLED')
    ),
    CONSTRAINT trace_previous_status_known CHECK (
        previous_status IS NULL
        OR previous_status IN ('PENDING', 'IN_PREPARATION', 'READY', 'DELIVERED', 'CANCELLED')
    ),
    CONSTRAINT one_row_per_status UNIQUE (order_id, new_status)
);

CREATE INDEX order_status_change_customer_idx
    ON order_status_change (customer_id, order_id, occurred_at);

CREATE INDEX order_status_change_employee_idx
    ON order_status_change (employee_id, occurred_at)
    WHERE employee_id IS NOT NULL;
